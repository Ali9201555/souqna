export function getVehicleMake(id: string): VehicleMake | undefined {
  return VEHICLE_MAKES.find((m) => m.id === id);
}

export function getModelsForMake(makeId: string | null | undefined): VehicleModel[] {
  return (makeId ? getVehicleMake(makeId)?.models : undefined) ?? [];
}

export function getVehicleModel(makeId: string, modelId: string): VehicleModel | undefined {
  return getVehicleMake(makeId)?.models.find((m) => m.id === modelId);
}

export function modelLabel(model: VehicleModel, lang: Language): string {
  return lang === 'en' ? model.en : model.ar;
}
